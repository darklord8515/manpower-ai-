# Copies the company logos into the web app and generates their inline-SVG markup module.
# The originals (ALHAMRA-LOGO.svg, ALHAMRA-FAVICON-LOGO.svg at the repo root) are never edited.
# Re-run after replacing a logo:  powershell -File scripts/build-brand.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)
$publicBrand = Join-Path $root 'apps\web\public\brand'
New-Item -ItemType Directory -Force $publicBrand | Out-Null

function Read-Logo([string]$file) {
    $svg = [System.IO.File]::ReadAllText((Join-Path $root $file))
    $viewBox = [regex]::Match($svg, 'viewBox="([^"]+)"').Groups[1].Value
    $inner = [regex]::Match($svg, '<g id="Layer_1-2"[^>]*>(.*)</g></g></svg>', 'Singleline').Groups[1].Value
    # The artwork is white-only; drop the class attributes so the shapes inherit currentColor.
    $inner = [regex]::Replace($inner, '\s+class="[^"]*"', '')
    if (-not $viewBox -or -not $inner) { throw "Could not read $file" }
    [pscustomobject]@{ ViewBox = $viewBox; Inner = $inner }
}

Copy-Item (Join-Path $root 'ALHAMRA-LOGO.svg') $publicBrand -Force
Copy-Item (Join-Path $root 'ALHAMRA-FAVICON-LOGO.svg') $publicBrand -Force

$word = Read-Logo 'ALHAMRA-LOGO.svg'
$mark = Read-Logo 'ALHAMRA-FAVICON-LOGO.svg'
$ts = @"
// GENERATED by scripts/build-brand.ps1 from the original logo SVGs. Do not edit by hand.
// The artwork is white-only; components render it with fill=currentColor.

export const WORDMARK = {
  viewBox: "$($word.ViewBox)",
  inner: $($word.Inner | ConvertTo-Json),
} as const;

export const MARK = {
  viewBox: "$($mark.ViewBox)",
  inner: $($mark.Inner | ConvertTo-Json),
} as const;
"@
# Browser-tab icon: white-only artwork vanishes on a light tab, so it sits on a dark rounded square.
$tab = "<svg xmlns='http://www.w3.org/2000/svg' viewBox='-12 -8 89.47 91.87'><rect x='-12' y='-8' width='89.47' height='91.87' rx='14' fill='#1c1917'/><g fill='#fff'>$($mark.Inner.Replace('"', "'"))</g></svg>"
[System.IO.File]::WriteAllText((Join-Path $publicBrand 'favicon-tab.svg'), $tab, $utf8)

$out = Join-Path $root 'apps\web\components\brand\logo-markup.ts'
New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
[System.IO.File]::WriteAllText($out, $ts, $utf8)
Write-Host "Wrote $out and copied the originals to apps/web/public/brand/"
